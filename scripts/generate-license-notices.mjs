import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const normalize = text => text.replace(/\r\n/g, "\n").replace(/[ \t]+$/gm, "").trimEnd() + "\n";
const result = spawnSync("cargo-about", [
  "generate", "--manifest-path", "src-tauri/Cargo.toml", "--locked", "--fail", "--format", "json",
], { cwd: root, encoding: "utf8", maxBuffer: 20 * 1024 * 1024 });
if (result.error) throw result.error;
if (result.status !== 0) throw new Error(result.stderr);
const report = JSON.parse(result.stdout);
const sections = report.licenses.map(license => {
  const crates = license.used_by.map(item => `${item.crate.name} ${item.crate.version}`).sort().join("\n");
  return `${license.name} (${license.id})\nUsed by:\n${crates}\n\n${license.text}`;
});
const rustLock = createHash("sha256").update(readFileSync(join(root, "src-tauri/Cargo.lock"))).digest("hex");
writeFileSync(join(root, "licenses/RUST_DEPENDENCIES.txt"), normalize([
  "Daylight — Rust dependency license notices",
  "Generated by cargo-about 0.9.2 for aarch64-apple-darwin, including build dependencies.",
  `Cargo.lock SHA-256: ${rustLock}`,
  "For crate sources, the locked versions are available on https://crates.io and through cargo vendor.",
  ...sections,
].join("\n\n")));

const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
const npm = [];
for (const [path, item] of Object.entries(lock.packages)) {
  if (!path || item.dev) continue;
  const directory = join(root, path);
  const names = readdirSync(directory).filter(name => /^(licen[cs]e|notice|copying)/i.test(name));
  if (!names.length) throw new Error(`Missing license files for ${path}`);
  npm.push(`${path.replace(/^node_modules\//, "")} ${item.version} — ${item.license}\n\n` +
    names.sort().map(name => `${name}\n\n${readFileSync(join(directory, name), "utf8")}`).join("\n\n"));
}
const npmLock = createHash("sha256").update(readFileSync(join(root, "package-lock.json"))).digest("hex");
writeFileSync(join(root, "licenses/NPM_DEPENDENCIES.txt"), normalize([
  "Daylight — runtime npm dependency license notices",
  `package-lock.json SHA-256: ${npmLock}`,
  ...npm,
].join("\n\n")));
console.log(`Generated ${report.licenses.length} Rust license sections and ${npm.length} runtime npm notices.`);
